// Renders an emote clip for previews: window.preview(clip, t, yaw)
import * as THREE from "three";
import { makePlayer, samplePose } from "./emoterig.js";
const canvas = document.getElementById("c");
const renderer = new THREE.WebGLRenderer({ canvas, antialias: true, preserveDrawingBuffer: true });
renderer.setSize(360, 460);
renderer.setClearColor(0x16161c);
const scene = new THREE.Scene();
scene.add(new THREE.AmbientLight(0xffffff, 1.6));
const sun = new THREE.DirectionalLight(0xffffff, 1.8);
sun.position.set(20, 40, 30);
scene.add(sun);
const cam = new THREE.PerspectiveCamera(32, 360 / 460, 1, 500);
cam.position.set(0, 20, 72);
cam.lookAt(0, 15, 0);
const ground = new THREE.Mesh(new THREE.CircleGeometry(16, 40), new THREE.MeshBasicMaterial({ color: 0x24242c }));
ground.rotation.x = -Math.PI / 2;
scene.add(ground);
const tex = new THREE.TextureLoader().load(window.SKIN, () => (window.ready = true));
tex.magFilter = THREE.NearestFilter;
tex.minFilter = THREE.NearestFilter;
tex.flipY = false;
tex.colorSpace = THREE.SRGBColorSpace;
const player = makePlayer(tex, false);
scene.add(player.group);
window.preview = (clip, t, yaw = 0) => {
  player.pose(samplePose(clip, t));
  player.group.rotation.y = yaw;
  renderer.render(scene, cam);
};
